async function generateRpcActions(): Promise<void> {
  const src = await fs.readFile(
    path.join(REPO_ROOT, "packages/contracts/src/rpc.ts"),
    "utf8",
  );
  const blockMatch = src.match(
    /export interface RpcRequestPayloads \{([\s\S]*?)\n\}/,
  );
  if (!blockMatch) {
    throw new Error("[generate-content] Could not find RpcRequestPayloads in packages/contracts/src/rpc.ts");
  }
  const entries: { name: string; payload: string }[] = [];
  for (const m of blockMatch[1]!.matchAll(/^\s*"([a-zA-Z.]+)":\s*(.+);\s*$/gm)) {
    entries.push({ name: m[1]!, payload: m[2]! });
  }
  if (entries.length === 0) {
    throw new Error("[generate-content] Parsed zero RPC actions out of RpcRequestPayloads — the regex likely no longer matches the file's shape.");
  }

  const problems: string[] = [];
  const actionNames = new Set(entries.map((e) => e.name));
  for (const name of actionNames) {
    if (!(name in rpcSummaries)) problems.push(`rpc.ts declares "${name}" with no docs summary`);
  }
  for (const name of Object.keys(rpcSummaries)) {
    if (!actionNames.has(name)) problems.push(`docs summary for "${name}" has no matching entry in RpcRequestPayloads`);
  }
  if (problems.length > 0) {
    throw new Error(`[generate-content] RPC reference drifted from source:\n  ${problems.join("\n  ")}`);
  }

  const rows = entries.map((e) => ({
    name: e.name,
    payload: e.payload === "never" ? "none" : e.payload,
    summary: rpcSummaries[e.name]!,
  }));

  await writeGenerated(
    "rpc-actions.ts",
    `export interface RpcActionRow {
  name: string;
  payload: string;
  summary: string;
}

export const rpcActions: RpcActionRow[] = ${JSON.stringify(rows, null, 2)};

export const rpcActionCount: number = rpcActions.length;
`,
  );
}

// --- 6. Commands ----------------------------------------------------------------

interface CommandEntry {
  module: string;
  name: string;
  description: string;
  requiredPermit: string | null;
  subcommands: string[];
}

/** Extracts the balanced `{ ... }` object literal that follows `@ApplyOptions<...>(`. */
function extractApplyOptionsBlocks(src: string): string[] {
  const blocks: string[] = [];
  const marker = "@ApplyOptions<";
  let searchFrom = 0;
  for (;;) {
    const markerIdx = src.indexOf(marker, searchFrom);
    if (markerIdx === -1) break;
    const openParen = src.indexOf("(", markerIdx);
    const openBrace = src.indexOf("{", openParen);
    if (openParen === -1 || openBrace === -1) break;
    let depth = 0;
    let i = openBrace;
    for (; i < src.length; i++) {
      if (src[i] === "{") depth++;
      else if (src[i] === "}") {
        depth--;
        if (depth === 0) break;
      }
    }
    blocks.push(src.slice(openBrace, i + 1));
    searchFrom = i + 1;
  }
  return blocks;
}

function firstMatch(block: string, re: RegExp): string | null {
  const m = block.match(re);
  return m ? m[1]! : null;
}

async function generateCommands(manifests: Manifest[]): Promise<void> {
  const byModule = new Map(manifests.map((m) => [m.name, m]));
  const commands: CommandEntry[] = [];

  for (const moduleName of MODULE_NAMES) {
    const dir = path.join(REPO_ROOT, "packages/core/src/modules", moduleName, "commands");
    let files: string[];
    try {
      files = (await fs.readdir(dir)).filter((f) => f.endsWith(".ts"));
    } catch {
      continue;
    }
    for (const file of files) {
      const src = await fs.readFile(path.join(dir, file), "utf8");
      for (const block of extractApplyOptionsBlocks(src)) {
        const name = firstMatch(block, /name:\s*"([^"]+)"/);
        const description = firstMatch(block, /description:\s*"((?:[^"\\]|\\.)*)"/);
        if (!name || !description) continue;
        const requiredPermit = firstMatch(block, /requiredPermit:\s*"([^"]+)"/);
        const subcommandsBlock = block.match(/subcommands:\s*\[([\s\S]*?)\]/);
        const subcommands = subcommandsBlock
          ? [...subcommandsBlock[1]!.matchAll(/name:\s*"([^"]+)"/g)].map((m) => m[1]!)
          : [];
        commands.push({
          module: moduleName,
          name,
          description: description.replace(/\\"/g, '"'),
          requiredPermit,
          subcommands,
        });
      }
    }
  }

  if (commands.length === 0) {
    throw new Error("[generate-content] Parsed zero commands out of packages/core/src/modules/*/commands — the extractor likely no longer matches the source shape.");
  }

  commands.sort((a, b) => a.module.localeCompare(b.module) || a.name.localeCompare(b.name));

  const groups = MODULE_NAMES.map((name) => {
    const manifest = byModule.get(name)!;
    return {
      module: name,
      displayName: manifest.displayName,
      emoji: manifest.emoji,
      commands: commands.filter((c) => c.module === name),
    };
  }).filter((g) => g.commands.length > 0);

  await writeGenerated(
    "commands.ts",
    `export interface CommandRow {
  module: string;
  name: string;
  description: string;
  requiredPermit: string | null;
  subcommands: string[];
}

export interface CommandGroup {
  module: string;
  displayName: string;
  emoji: string;
  commands: CommandRow[];
}

export const commandGroups: CommandGroup[] = ${JSON.stringify(groups, null, 2)};

export const commandCount: number = ${commands.length};
`,
  );
}

async function main() {
  const manifests = await loadManifests();
  await Promise.all([
    generateModules(manifests),
    generateDataPrivacy(manifests),
    generatePermits(),
    generateEnvVars(),
    generateRpcActions(),
    generateCommands(manifests),
  ]);
  console.log(`[generate-content] wrote generated docs data to ${path.relative(REPO_ROOT, OUT_DIR)}/`);
}

await main();
