#!/usr/bin/env bun
// Build-time generator: reads real source (module manifests, permit-node
// vocabulary, the RPC contract, env var readers, and command decorators) and
// writes typed data modules under src/generated/ for the reference pages to
// import. Gitignored, regenerated on every `bun run generate` (also run by
// `dev`/`build`) — never hand-edit anything under src/generated/.

import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DOCS_ROOT = path.resolve(fileURLToPath(new URL("../", import.meta.url)));
const REPO_ROOT = path.resolve(DOCS_ROOT, "../../");
const OUT_DIR = path.join(DOCS_ROOT, "src/generated");

async function writeGenerated(file: string, content: string): Promise<void> {
  await fs.mkdir(OUT_DIR, { recursive: true });
  const header = `// GENERATED by apps/docs/scripts/generate-content.ts — do not edit by hand.\n`;
  await fs.writeFile(path.join(OUT_DIR, file), header + content, "utf8");
}

const MODULE_NAMES = [
  "afk", "core", "dashboard", "economy", "filter", "logging", "mod",
  "reactionroles", "security", "tempvc", "utility", "welcome",
] as const;

interface Manifest {
  name: string;
  displayName: string;
  emoji: string;
  description: string;
  short: string;
  endUserDataStatement?: string;
  disableable: boolean;
  category: string;
  configFields: {
    key: string;
    type: string;
    label: string;
    description: string;
    group?: string;
    default?: unknown;
  }[];
}

async function loadManifests(): Promise<Manifest[]> {
  const manifests: Manifest[] = [];
  for (const name of MODULE_NAMES) {
    const p = path.join(REPO_ROOT, "packages/core/src/modules", name, "manifest.json");
    const raw = await fs.readFile(p, "utf8");
    manifests.push(JSON.parse(raw) as Manifest);
  }
  return manifests;
}

// --- 1. Modules -------------------------------------------------------------

async function generateModules(manifests: Manifest[]): Promise<void> {
  const rows = manifests.map((m) => ({
    name: m.name,
    displayName: m.displayName,
    emoji: m.emoji,
    description: m.description,
    short: m.short,
    category: m.category,
    disableable: m.disableable,
    configFieldCount: m.configFields.length,
  }));
  await writeGenerated(
    "modules.ts",
    `export interface ModuleSummary {
  name: string;
  displayName: string;
  emoji: string;
  description: string;
  short: string;
  category: string;
  disableable: boolean;
  configFieldCount: number;
}

export const modules: ModuleSummary[] = ${JSON.stringify(rows, null, 2)};
`,
  );
}

// --- 2. Data and privacy -----------------------------------------------------

async function generateDataPrivacy(manifests: Manifest[]): Promise<void> {
  const rows = manifests.map((m) => ({
    name: m.name,
    displayName: m.displayName,
    statement: m.endUserDataStatement ?? null,
  }));
  await writeGenerated(
    "data-privacy.ts",
    `export interface DataPrivacyRow {
  name: string;
  displayName: string;
  /** null when the module's manifest.json declares no endUserDataStatement. */
  statement: string | null;
}

export const dataPrivacyRows: DataPrivacyRow[] = ${JSON.stringify(rows, null, 2)};
`,
  );
}

// --- 3. Permit nodes ----------------------------------------------------------

async function generatePermits(): Promise<void> {
  const mod = await import(
    path.join(REPO_ROOT, "packages/contracts/src/permit-nodes.ts")
  );
  const groups = mod.KnownPermitNodeGroups as { prefix: string; nodes: string[] }[];
  await writeGenerated(
    "permits.ts",
    `export interface PermitNodeGroup {
  prefix: string;
  nodes: string[];
}

export const permitNodeGroups: PermitNodeGroup[] = ${JSON.stringify(groups, null, 2)};

export const permitNodeCount: number = permitNodeGroups.reduce(
  (total, group) => total + group.nodes.length,
  0,
);
`,
  );
}

